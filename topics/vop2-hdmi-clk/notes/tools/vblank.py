"""Measure the real pixel clock of a running CRTC from its vblank timestamps.

  vblank.py <pipe> [seconds]      pipe = CRTC index (0 = video_port0 = HDMI-A-1 here)
The vblank interrupt is generated by the VOP timing generator, which runs on DCLK, so
refresh = DCLK / (htotal * vtotal) and DCLK = refresh * htotal * vtotal, with htotal/vtotal
taken from the CRTC's mode in debugfs state. Prints one JSON line.
"""
import ctypes, fcntl, json, os, re, sys, time


class Req(ctypes.Structure):
    _fields_ = [("type", ctypes.c_uint), ("sequence", ctypes.c_uint), ("signal", ctypes.c_ulong)]


class Rep(ctypes.Structure):
    _fields_ = [("type", ctypes.c_uint), ("sequence", ctypes.c_uint), ("tval_sec", ctypes.c_long),
                ("tval_usec", ctypes.c_long)]


class WV(ctypes.Union):
    _fields_ = [("request", Req), ("reply", Rep)]


DRM_IOCTL_WAIT_VBLANK = 0xc018643a   # _IOWR('d', 0x3a, union drm_wait_vblank), 24 bytes on arm64
RELATIVE = 0x1
HIGH_CRTC_SHIFT = 1


def wait(fd, pipe, n=1):
    w = WV()
    t = RELATIVE
    if pipe == 1:
        t |= 0x20000000                  # _DRM_VBLANK_SECONDARY
    elif pipe > 1:
        t |= (pipe << HIGH_CRTC_SHIFT) & 0x3e
    w.request.type = t
    w.request.sequence = n
    fcntl.ioctl(fd, DRM_IOCTL_WAIT_VBLANK, w)
    return w.reply.sequence, w.reply.tval_sec + w.reply.tval_usec / 1e6


def mode_of(pipe):
    st = open("/sys/kernel/debug/dri/0/state").read()
    crtcs = re.findall(r"crtc\[\d+\]: (\S+)\n((?:\t.*\n)+)", st)
    name, body = crtcs[pipe]
    m = re.search(r'mode: "[^"]*": (\d+) (\d+) (\d+) \d+ \d+ (\d+) (\d+) \d+ \d+ (\d+)', body)
    return name, dict(vrefresh=int(m[1]), clock_khz=int(m[2]), hdisplay=int(m[3]), htotal=int(m[4]),
                      vdisplay=int(m[5]), vtotal=int(m[6]))


def main(a):
    pipe = int(a[0])
    secs = float(a[1]) if len(a) > 1 else 5
    name, m = mode_of(pipe)
    fd = os.open("/dev/dri/card0", os.O_RDWR)
    wait(fd, pipe)
    s0, t0 = wait(fd, pipe)
    end = t0 + secs
    s1, t1 = s0, t0
    while t1 < end:                      # the kernel gives up on a single wait after 3 s
        s1, t1 = wait(fd, pipe, max(1, m["vrefresh"] // 2))
    hz = (s1 - s0) / (t1 - t0)
    dclk = hz * m["htotal"] * m["vtotal"]
    print(json.dumps(dict(crtc=name, mode=m, frames=s1 - s0, seconds=round(t1 - t0, 6), refresh_hz=round(hz, 5),
                          measured_pixclk_khz=round(dclk / 1000, 1),
                          error_ppm=round((dclk / 1000 / m["clock_khz"] - 1) * 1e6))))


if __name__ == "__main__":
    main(sys.argv[1:])
