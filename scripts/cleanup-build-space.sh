# Free disk space by deleting regenerable kernel build output under build/.
# Only the targets listed below are touched:
#  - kernel O= build directories: deleted unless a git checkout, a kernel
#    source tree, in use by a running process, or changed in the last 30 min;
#  - superseded test kernel packages;
#  - git worktrees whose commits are in patches/linux: removed with
#    "git worktree remove" (the branch is kept), only if they have no
#    uncommitted changes and nothing is using them.
#   scripts/cleanup-build-space.sh        # shows the plan, asks once, deletes
#   scripts/cleanup-build-space.sh --yes  # no question
set -euo pipefail
TOP=$(cd "$(dirname "$0")/.." && pwd)
B=$TOP/build
YES=0; [ "${1:-}" = --yes ] && YES=1

TARGETS=(
  k9test-out              # k9 test kernel build output (kernel 9 is built in build/linux)
  hdmi-frl-pll-out        # standalone V0PLL kernel build (patches are 1911-1915)
)
# superseded k9 test kernel packages (kernel 9 = the same tree, in out/debs)
mapfile -t DEBS < <(ls "$B"/linux-*_7.3.0-9test_arm64.deb "$B"/k9test-noccu/*.deb 2>/dev/null || true)
# worktrees whose commits are now patches 1901-1916 / 2001-2017
WORKTREES=(wt-test-k9 wt-usb-resume wt-dw-dp-aux wt-klog-19b wt-hdmi-ddc wt-vop2-uf2
           wt-hdmi-frl-pll wt-hdmi-10bpc)

# a process has its cwd under the path or names it on its command line
in_use() {
  local p=$1 d
  for d in /proc/[0-9]*; do
    [ "$d" = "/proc/$$" ] && continue
    case "$(readlink "$d/cwd" 2>/dev/null)" in "$p"|"$p"/*) return 0;; esac
    tr "\\0" " " 2>/dev/null < "$d/cmdline" | grep -qF -- "$p" && return 0
  done
  return 1
}

ok=(); wts=(); skip=()
for t in "${TARGETS[@]}"; do
  p=$B/$t
  [ -e "$p" ] || continue
  if git -C "$p" rev-parse --is-inside-work-tree >/dev/null 2>&1 &&
     [ "$(git -C "$p" rev-parse --show-toplevel)" = "$(realpath "$p")" ]; then
    skip+=("$t: git checkout"); continue
  fi
  # a kernel source tree has MAINTAINERS and Kconfig; an O= build directory has
  # neither, only kbuild's .config and its generated wrapper Makefile
  if [ -e "$p/MAINTAINERS" ] || [ -e "$p/Kconfig" ]; then
    skip+=("$t: kernel source tree"); continue
  fi
  if [ ! -e "$p/.config" ] || ! grep -q 'Automatically generated by' "$p/Makefile" 2>/dev/null; then
    skip+=("$t: not a kernel build directory"); continue
  fi
  if in_use "$p"; then skip+=("$t: in use by a running process"); continue; fi
  if [ -n "$(find "$p" -newermt '-30 minutes' -print -quit 2>/dev/null)" ]; then
    skip+=("$t: changed in the last 30 minutes"); continue
  fi
  ok+=("$p")
done
for t in "${WORKTREES[@]}"; do
  p=$B/$t
  [ -e "$p" ] || continue
  if [ "$(git -C "$p" rev-parse --show-toplevel 2>/dev/null)" != "$(realpath "$p")" ]; then
    skip+=("$t: not a git worktree"); continue
  fi
  if [ -n "$(git -C "$p" status --porcelain 2>/dev/null)" ]; then
    skip+=("$t: has uncommitted changes"); continue
  fi
  if in_use "$p"; then skip+=("$t: in use by a running process"); continue; fi
  wts+=("$p")
done

echo "disk before: $(df -h / | awk 'NR==2{print $3" used, "$5}')"
echo "will delete:"
for p in "${ok[@]}" "${DEBS[@]}"; do printf '  %6s  %s\n' "$(du -sh "$p" 2>/dev/null | cut -f1)" "${p#"$TOP"/}"; done
for p in "${wts[@]}"; do
  printf '  %6s  %s (worktree; branch %s kept)\n' "$(du -sh "$p" 2>/dev/null | cut -f1)" "${p#"$TOP"/}" \
    "$(git -C "$p" branch --show-current)"
done
for s in "${skip[@]}"; do echo "  skipped  $s"; done
[ $(( ${#ok[@]} + ${#DEBS[@]} + ${#wts[@]} )) -gt 0 ] || { echo "nothing to delete"; exit 0; }
if [ $YES = 0 ]; then
  read -r -p "delete these? [y/N] " a
  [ "$a" = y ] || [ "$a" = Y ] || { echo "nothing deleted"; exit 0; }
fi
[ ${#ok[@]} -eq 0 ] || rm -rf -- "${ok[@]}"
[ ${#DEBS[@]} -eq 0 ] || rm -f -- "${DEBS[@]}"
rmdir "$B/k9test-noccu" 2>/dev/null || true
for p in "${wts[@]}"; do git -C "$p" worktree remove "$p"; done
echo "disk after:  $(df -h / | awk 'NR==2{print $3" used, "$5}')"
