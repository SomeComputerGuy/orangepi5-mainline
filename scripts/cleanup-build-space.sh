# Free disk space by deleting regenerable kernel build output under build/.
# Only the targets listed below are removed, and each one is skipped if it
# is a git checkout, holds real (non-generated) sources, or changed in the
# last 6 hours (a build or agent may be using it).
#   scripts/cleanup-build-space.sh        # shows the plan, asks once, deletes
#   scripts/cleanup-build-space.sh --yes  # no question
set -euo pipefail
TOP=$(cd "$(dirname "$0")/.." && pwd)
B=$TOP/build
YES=0; [ "${1:-}" = --yes ] && YES=1

TARGETS=(
  wt-integration-7.3      # old integration kernel build output
  wt-hdmi-frl-7.3         # old HDMI FRL kernel build output
  wt-multicore            # old multicore kernel build output
  wt-gpu-npu-7.3          # old GPU/NPU kernel build output
  wt-rkvenc-7.3           # old VEPU580 kernel build output
  wt-suspend-test/kbuild  # suspend test kernel build (fixes landed as 1103/1104)
  wt-suspend-test/kbuild-susp
)
# superseded suspend test kernel packages (incl. 1.7 GB -dbg packages)
mapfile -t DEBS < <(ls "$B"/wt-suspend-test/linux-image-*suspend_arm64.deb \
                       "$B"/wt-suspend-test/linux-image-*susp2_arm64.deb 2>/dev/null || true)

ok=(); skip=()
for t in "${TARGETS[@]}"; do
  p=$B/$t
  [ -e "$p" ] || continue
  if git -C "$p" rev-parse --is-inside-work-tree >/dev/null 2>&1 &&
     [ "$(git -C "$p" rev-parse --show-toplevel)" = "$(realpath "$p")" ]; then
    skip+=("$t: git checkout"); continue
  fi
  if [ -n "$(find "$p" -newermt '-6 hours' -print -quit 2>/dev/null)" ]; then
    skip+=("$t: changed in the last 6 hours"); continue
  fi
  # a kernel source tree has MAINTAINERS and Kconfig; an O= build directory has
  # neither, only kbuild's .config and its generated wrapper Makefile
  if [ -e "$p/MAINTAINERS" ] || [ -e "$p/Kconfig" ]; then
    skip+=("$t: kernel source tree"); continue
  fi
  if [ ! -e "$p/.config" ] || ! grep -q 'Automatically generated by' "$p/Makefile" 2>/dev/null; then
    skip+=("$t: not a kernel build directory"); continue
  fi
  ok+=("$p")
done

echo "disk before: $(df -h / | awk 'NR==2{print $3" used, "$5}')"
echo "will delete:"
for p in "${ok[@]}" "${DEBS[@]}"; do printf '  %6s  %s\n' "$(du -sh "$p" 2>/dev/null | cut -f1)" "${p#"$TOP"/}"; done
for s in "${skip[@]}"; do echo "  skipped  $s"; done
[ $(( ${#ok[@]} + ${#DEBS[@]} )) -gt 0 ] || { echo "nothing to delete"; exit 0; }
if [ $YES = 0 ]; then
  read -r -p "delete these? [y/N] " a
  [ "$a" = y ] || [ "$a" = Y ] || { echo "nothing deleted"; exit 0; }
fi
rm -rf -- "${ok[@]}"
[ ${#DEBS[@]} -eq 0 ] || rm -f -- "${DEBS[@]}"
echo "disk after:  $(df -h / | awk 'NR==2{print $3" used, "$5}')"
