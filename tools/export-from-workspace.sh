#!/bin/bash
# Refresh this repository from the Orange Pi 5 workspace, then scan it.
#
#   tools/export-from-workspace.sh [--workspace DIR] [--commit] [--branches]
#
#   --workspace DIR  workspace root (default ~/orangepi5); read only
#   --commit         commit the refresh as the repository owner if anything changed
#   --branches       also recreate the kernel fork branches (.work/linux) and
#                    verify every topic's tree (about 2 minutes)
#
# What it regenerates (and overwrites): scripts/, install-deps.sh, patches/,
# overlay/, cidata/, docs/workspace/, docs/image-kernel/, topics/, STATUS.md.
# Hand-written files are not touched. Needs .work/private/ (not published):
# see tools/export/README.md.
set -euo pipefail
REPO=$(cd "$(dirname "$0")/.." && pwd)
WS=$HOME/orangepi5 COMMIT=0 BRANCHES=0
while [ $# -gt 0 ]; do
  case "$1" in
    --workspace) WS=$2; shift 2 ;;
    --commit) COMMIT=1; shift ;;
    --branches) BRANCHES=1; shift ;;
    -h|--help) sed -n '2,15p' "$0"; exit 0 ;;
    *) echo "unknown option $1"; exit 1 ;;
  esac
done
cd "$REPO"
echo "==> Exporting from $WS"
python3 -I tools/export/export.py --workspace "$WS"
if [ $BRANCHES = 1 ]; then
  echo "==> Recreating kernel branches"
  tools/recreate-kernel-branches.sh --linux "$WS/src/linux"
fi
echo "==> Secret scan"
tools/secret-scan.sh
echo "==> Changes"
git add -A
git status --short | sed -n '1,40p'
n=$(git status --short | wc -l)
echo "$n paths changed"
if [ $COMMIT = 1 ] && [ "$n" -gt 0 ]; then
  git -c user.name="Arun Iyengar" -c user.email=aiyengar1990@gmail.com commit -q \
    -m "Refresh from the workspace ($(date -u +%F))" \
    -m "Regenerated by tools/export-from-workspace.sh." \
    -m "Assisted-by: Claude:claude-opus-5-5"
  git log --oneline -1
fi
